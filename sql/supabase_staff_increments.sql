-- Shibra Campus staff salary increments.
-- Run after supabase_roles.sql and supabase_staff_attendance.sql.
-- Schedules one percentage OR fixed-amount increment per selected staff member.

begin;

create table if not exists public.staff_salary_increments (
    id bigint generated by default as identity primary key,
    staff_id text not null,
    staff_name text not null,
    designation text,
    effective_month text not null check (effective_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    method text not null check (method in ('percentage', 'fixed')),
    percentage numeric not null default 0 check (percentage >= 0),
    fixed_amount numeric not null default 0 check (fixed_amount >= 0),
    previous_salary numeric not null check (previous_salary >= 0),
    increase_amount numeric not null check (increase_amount > 0),
    new_salary numeric not null check (new_salary > previous_salary),
    notes text not null,
    created_at timestamptz not null default now(),
    unique (staff_id, effective_month),
    check (
        (method = 'percentage' and percentage > 0 and fixed_amount = 0)
        or (method = 'fixed' and fixed_amount > 0 and percentage = 0)
    )
);

create index if not exists staff_salary_increments_effective_idx
    on public.staff_salary_increments (staff_id, effective_month desc);

alter table public.staff_salary_increments enable row level security;
revoke all on table public.staff_salary_increments from anon;
revoke insert, update, delete on table public.staff_salary_increments from authenticated;
grant select on table public.staff_salary_increments to authenticated;

drop policy if exists staff_salary_increments_select on public.staff_salary_increments;
create policy staff_salary_increments_select on public.staff_salary_increments
    for select to authenticated
    using (public.app_has_page_permission('staff', 'v') or public.app_has_page_permission('staff', 'e'));

create or replace function public.schedule_staff_salary_increment(
    p_staff_ids text[],
    p_method text,
    p_value numeric,
    p_effective_month text,
    p_notes text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
    v_staff record;
    v_count integer := 0;
    v_previous numeric;
    v_increase numeric;
    v_new_salary numeric;
    v_results jsonb := '[]'::jsonb;
begin
    if not public.app_has_page_permission('staff', 'e') then
        raise exception 'Staff Edit permission is required to apply salary increments.';
    end if;
    if p_staff_ids is null or cardinality(p_staff_ids) = 0
       or cardinality(p_staff_ids) <> (
            select count(distinct selected.staff_id)
            from unnest(p_staff_ids) as selected(staff_id)
       ) then
        raise exception 'Select one or more different staff members.';
    end if;
    if p_effective_month is null
       or p_effective_month !~ '^[0-9]{4}-(0[1-9]|1[0-2])$' then
        raise exception 'Effective month must use YYYY-MM format.';
    end if;
    if p_notes is null or length(trim(p_notes)) = 0 then
        raise exception 'Enter the reason for this salary increment.';
    end if;
    if p_value is null or p_value <= 0 then
        raise exception 'Increment value must be greater than zero.';
    end if;
    if round(p_value, 2) <> p_value then
        raise exception 'Increment value can have at most two decimal places.';
    end if;
    if p_method = 'percentage' and p_value > 100 then
        raise exception 'Percentage increment cannot exceed 100%%.';
    elsif p_method is null or p_method not in ('percentage', 'fixed') then
        raise exception 'Choose either a percentage or fixed-amount increment.';
    end if;

    for v_staff in
        select s.staff_id, s.staff_name, s.designation, coalesce(s.base_salary, 0) as base_salary
        from public.staff s
        where s.staff_id = any(p_staff_ids)
          and lower(coalesce(s.status, 'Active')) = 'active'
        order by s.staff_id
        for update
    loop
        if exists (
            select 1 from public.staff_salary_increments i
            where i.staff_id = v_staff.staff_id
              and i.effective_month = p_effective_month
        ) then
            raise exception 'An increment already exists for % in %.', v_staff.staff_name, p_effective_month;
        end if;
        if exists (
            select 1 from public.staff_salary_increments i
            where i.staff_id = v_staff.staff_id
              and i.effective_month > p_effective_month
        ) then
            raise exception 'A later increment already exists for %. Correct its effective month from increment history before adding this backdated increment.', v_staff.staff_name;
        end if;

        select i.new_salary into v_previous
        from public.staff_salary_increments i
        where i.staff_id = v_staff.staff_id
          and i.effective_month < p_effective_month
        order by i.effective_month desc
        limit 1;
        v_previous := coalesce(v_previous, v_staff.base_salary);
        v_increase := case
            when p_method = 'percentage' then round(v_previous * p_value / 100, 2)
            else round(p_value, 2)
        end;
        if v_increase <= 0 then
            raise exception 'The calculated increment for % is less than PKR 0.01.', v_staff.staff_name;
        end if;
        v_new_salary := v_previous + v_increase;

        insert into public.staff_salary_increments (
            staff_id, staff_name, designation, effective_month, method,
            percentage, fixed_amount, previous_salary, increase_amount, new_salary, notes
        ) values (
            v_staff.staff_id, v_staff.staff_name, v_staff.designation, p_effective_month, p_method,
            case when p_method = 'percentage' then p_value else 0 end,
            case when p_method = 'fixed' then round(p_value, 2) else 0 end,
            v_previous, v_increase, v_new_salary, trim(p_notes)
        );
        v_results := v_results || jsonb_build_array(jsonb_build_object(
            'staff_id', v_staff.staff_id,
            'staff_name', v_staff.staff_name,
            'previous_salary', v_previous,
            'increase_amount', v_increase,
            'new_salary', v_new_salary,
            'effective_month', p_effective_month
        ));
        v_count := v_count + 1;
    end loop;

    if v_count <> cardinality(p_staff_ids) then
        raise exception 'One or more selected staff are missing or are not Active. No increments were saved.';
    end if;

    return v_results;
end;
$$;

revoke all on function public.schedule_staff_salary_increment(text[], text, numeric, text, text) from public, anon;
grant execute on function public.schedule_staff_salary_increment(text[], text, numeric, text, text) to authenticated;

create or replace function public.reschedule_staff_salary_increment(
    p_increment_id bigint,
    p_effective_month text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
    v_increment public.staff_salary_increments%rowtype;
    v_base_salary numeric;
    v_previous_salary numeric;
    v_increase numeric;
begin
    if not public.app_has_page_permission('staff', 'e') then
        raise exception 'Staff Edit permission is required to change an increment date.' using errcode = '42501';
    end if;
    if p_effective_month is null or p_effective_month !~ '^[0-9]{4}-(0[1-9]|1[0-2])$' then
        raise exception 'Effective month must use YYYY-MM format.' using errcode = '22023';
    end if;

    select * into v_increment
    from public.staff_salary_increments
    where id = p_increment_id
    for update;
    if not found then
        raise exception 'The selected salary increment was not found.' using errcode = 'P0002';
    end if;
    if v_increment.effective_month = p_effective_month then
        return jsonb_build_object('id', v_increment.id, 'effective_month', v_increment.effective_month);
    end if;
    if exists (
        select 1
        from public.staff_salary_increments i
        where i.staff_id = v_increment.staff_id
          and i.id <> v_increment.id
          and i.effective_month = p_effective_month
    ) then
        raise exception 'This staff member already has an increment in %.', p_effective_month using errcode = '23505';
    end if;
    if exists (
        select 1
        from public.staff_salary_increments i
        where i.staff_id = v_increment.staff_id
          and i.id <> v_increment.id
          and i.effective_month > p_effective_month
    ) then
        raise exception 'Move later increments first; salary increments must remain in date order.' using errcode = '22023';
    end if;

    select coalesce(s.base_salary, 0) into v_base_salary
    from public.staff s
    where s.staff_id = v_increment.staff_id
    for update;
    if not found then
        raise exception 'The staff member for this increment was not found.' using errcode = 'P0002';
    end if;

    select i.new_salary into v_previous_salary
    from public.staff_salary_increments i
    where i.staff_id = v_increment.staff_id
      and i.id <> v_increment.id
      and i.effective_month < p_effective_month
    order by i.effective_month desc
    limit 1;
    v_previous_salary := coalesce(v_previous_salary, v_base_salary);
    v_increase := case
        when v_increment.method = 'percentage' then round(v_previous_salary * v_increment.percentage / 100, 2)
        else round(v_increment.fixed_amount, 2)
    end;
    if v_increase <= 0 then
        raise exception 'The calculated increment must be greater than zero.' using errcode = '22023';
    end if;

    update public.staff_salary_increments
    set effective_month = p_effective_month,
        previous_salary = v_previous_salary,
        increase_amount = v_increase,
        new_salary = v_previous_salary + v_increase
    where id = v_increment.id;

    return jsonb_build_object(
        'id', v_increment.id,
        'effective_month', p_effective_month,
        'previous_salary', v_previous_salary,
        'increase_amount', v_increase,
        'new_salary', v_previous_salary + v_increase
    );
end;
$$;
revoke all on function public.reschedule_staff_salary_increment(bigint, text) from public, anon;
grant execute on function public.reschedule_staff_salary_increment(bigint, text) to authenticated;

notify pgrst, 'reload schema';
commit;
