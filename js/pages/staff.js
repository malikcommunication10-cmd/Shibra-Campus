async function repairUnpaidLeaveBonuses(rows) {
    const errors = [];
    for(const payrollRow of rows.filter(row =>
        row.status === 'Unpaid' &&
        row.bonus > 0 &&
        !qualifiesForNoLeaveBonus(row.absenceCount, row.excusedLeaves, row.leaves)
    )) {
        const corrected = calcPay(
            payrollRow.base, payrollRow.leaves, 0, payrollRow.fine, payrollRow.advance,
            payrollRow.lateCount, payrollRow.salaryDays, payrollRow.security, payrollRow.lateDeductionDays
        );
        try {
            const c = getSupabaseConfig();
            const response = await fetch(`${c.url}/rest/v1/payroll?id=eq.${encodeURIComponent(payrollRow.id)}`, {
                method: 'PATCH',
                headers: sbHeaders({ ...JSON_H, Prefer: 'return=representation' }),
                body: JSON.stringify({
                    bonus: 0,
                    net_salary: corrected.net,
                    notes: [payrollRow.notes, 'System correction: no-absence bonus removed because leave was recorded.'].filter(Boolean).join(' ')
                })
            });
            if(!response.ok) throw new Error(await response.text());
            const updatedRows = await response.json();
            if(!Array.isArray(updatedRows) || !updatedRows.length) throw new Error('The payroll row was not updated; check Staff Edit permission.');
            payrollRow.bonus = 0;
            payrollRow.net = corrected.net;
            payrollRow.notes = updatedRows[0].notes || payrollRow.notes;
        } catch(error) {
            errors.push(`${payrollRow.name} (${payrollRow.month}): ${error.message || 'update failed'}`);
        }
    }
    return errors;
}

