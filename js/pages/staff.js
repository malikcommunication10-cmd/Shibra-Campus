async function markMonthAttendancePresent() {
    if(!attendanceOk) { toast('Run the attendance setup SQL first.', false); return; }
    if(attendanceDirty) { toast('Save or discard the unsaved daily attendance changes before marking the month.', false); return; }
    const month = curMonth(), today = todayStr();
    if(monthStart(month) > today) { toast('Attendance cannot be marked for a future month.', false); return; }

    showLoading(`Loading ${monthLabel(month)} attendance...`);
    let toInsert;
    try {
        const response = await ERP.db.request('staff_attendance',
            `select=staff_id,attendance_date&attendance_date=gte.${monthStart(month)}&attendance_date=lte.${monthEnd(month)}`);
        if(!response.ok) throw new Error('Could not read monthly attendance: ' + await response.text());
        const rows = await response.json();
        if(!Array.isArray(rows)) throw new Error('Supabase returned invalid monthly attendance data.');
        const marked = new Set(rows.map(row => `${row.staff_id}|${String(row.attendance_date).slice(0, 10)}`));
        toInsert = [];
        monthSchoolDays(month).filter(date => date <= today).forEach(date => {
            attendanceStaff(date).forEach(member => {
                if(!marked.has(`${member.staffId}|${date}`)) {
                    toInsert.push({ staff_id: member.staffId, staff_name: member.name, attendance_date: date,
                        status: 'present', note: 'Marked Present using monthly attendance action.',
                        absence_exempt: false, late_exempt: false });
                }
            });
        });
    } catch(error) {
        toast(error.message || 'Could not load monthly attendance.', false);
        hideLoading();
        return;
    }
    hideLoading();

    if(!toInsert.length) {
        toast(`All applicable working dates for ${monthLabel(month)} are already marked.`);
        return;
    }
    confirmBox(
        `Mark ${toInsert.length} unmarked staff workday(s) as Present for ${monthLabel(month)}? Existing Present, Absent, and Late records will not change. Sundays and future dates are skipped. Existing payroll is not recalculated.`,
        'Mark Present',
        async () => {
            const button = $('markMonthPresentBtn');
            button.disabled = true;
            showLoading('Saving monthly attendance...');
            try {
                const c = getSupabaseConfig();
                for(let i = 0; i < toInsert.length; i += 250) {
                    const response = await fetch(`${c.url}/rest/v1/staff_attendance?on_conflict=staff_id,attendance_date`, {
                        method: 'POST',
                        headers: sbHeaders({ ...JSON_H, Prefer: 'resolution=ignore-duplicates,return=minimal' }),
                        body: JSON.stringify(toInsert.slice(i, i + 250))
                    });
                    if(!response.ok) throw new Error('Could not save monthly attendance: ' + await response.text());
                }
                if(attendanceDate.startsWith(month + '-')) await loadAttendance(attendanceDate);
                const refreshError = await refreshAttendanceRangeAfterSave();
                toast(`Monthly attendance saved: ${toInsert.length} unmarked workday(s) set to Present. Existing payroll was not recalculated.${refreshError}`, !refreshError);
            } catch(error) {
                toast(`${error.message || 'Could not save monthly attendance.'} Any completed batches are safe to retry; existing records were not overwritten.`, false);
            } finally {
                button.disabled = false;
                hideLoading();
            }
        }
    );
}
