async function changeSalaryIncrementMonth(id, currentMonth) {
    const month = await UI.prompt(`Enter the correct effective month for this increment (YYYY-MM). Current: ${currentMonth}`, { value: currentMonth, title: 'Effective month' });
    if(month === null || month.trim() === '' || month.trim() === currentMonth) return;
    const effectiveMonth = month.trim();
    if(!/^\d{4}-(0[1-9]|1[0-2])$/.test(effectiveMonth)) {
        toast('Enter the effective month in YYYY-MM format, for example 2026-02.', false);
        return;
    }
    if(!await UI.confirm(`Change this increment's effective month from ${currentMonth} to ${effectiveMonth}? Previously generated or paid payroll will remain unchanged.`)) return;
    showLoading('Updating increment effective month...');
    try {
        const c = getSupabaseConfig();
        const response = await fetch(`${c.url}/rest/v1/rpc/reschedule_staff_salary_increment`, {
            method: 'POST',
            headers: sbHeaders(JSON_H),
            body: JSON.stringify({ p_increment_id: id, p_effective_month: effectiveMonth })
        });
        if(!response.ok) throw new Error('Could not change the increment month: ' + await response.text());
        toast(`Increment effective month changed to ${monthLabel(effectiveMonth)}.`);
        await initStaff();
        showTab('staff');
        await openSalaryIncrement();
    } catch(error) {
        toast(error.message || 'Could not change the increment month.', false);
    } finally {
        hideLoading();
    }
}
function confirmSalaryIncrement() {
    if(!incrementsOk) { toast('Increment setup is not available. Run its SQL migration first.', false); return; }
    const staffIds = [...document.querySelectorAll('[data-increment-staff]:checked')].map(box => box.dataset.incrementStaff);
    const methodInput = document.querySelector('input[name="incrementMethod"]:checked');
    const method = methodInput ? methodInput.value : '';
    const value = Number($('incrementValue').value);
    const month = $('incrementMonth').value;
    const notes = $('incrementNotes').value.trim();
    if(!staffIds.length) { toast('Select at least one active staff member.', false); return; }
    if(!Number.isFinite(value) || value <= 0 || (method === 'percentage' && value > 100) || Math.round(value * 100) / 100 !== value) {
        toast(method === 'percentage' ? 'Enter a percentage from 0.01 to 100, with at most two decimal places.' : 'Enter a fixed amount greater than zero, with at most two decimal places.', false);
        return;
    }
    if(!/^\d{4}-(0[1-9]|1[0-2])$/.test(month)) {
        toast('Choose an effective month in YYYY-MM format.', false); return;
    }
    if(!notes) { toast('Enter a reason for this salary increment.', false); $('incrementNotes').focus(); return; }
    const count = staffIds.length;
    confirmBox(`Save ${method === 'percentage' ? `${fmt(value)}%` : `PKR ${fmt(value)}`} increment for ${count} staff member(s), effective ${monthLabel(month)}? Backdating changes future payroll calculations, but existing payroll will not change.`, 'Save increment', () => saveSalaryIncrement(staffIds, method, value, month, notes));
}
async function saveSalaryIncrement(staffIds, method, value, month, notes) {
    closeModal('salaryIncrementModal');
    showLoading('Saving salary increments...');
    try {
        const c = getSupabaseConfig();
        const response = await fetch(`${c.url}/rest/v1/rpc/schedule_staff_salary_increment`, {
            method: 'POST', headers: sbHeaders(JSON_H),
            body: JSON.stringify({ p_staff_ids: staffIds, p_method: method, p_value: value, p_effective_month: month, p_notes: notes })
        });
        if(!response.ok) throw new Error('Could not save salary increments: ' + await response.text());
        const result = await response.json();
        if(!Array.isArray(result) || result.length !== staffIds.length) throw new Error('Supabase did not confirm every selected increment. Refresh and review increment history.');
        toast(`Salary increment saved for ${result.length} staff member(s), effective ${monthLabel(month)}.`);
        await initStaff();
        showTab('staff');
        await openSalaryIncrement();
    } catch(error) {
        toast(error.message || 'Could not save salary increments.', false);
    } finally {
        hideLoading();
    }
}

