async function generatePayroll() {
    if(!payrollOk) { showTab('payroll'); toast('Please run the one-time SQL at the top of the page first.', false); window.scrollTo({ top: 0 }); return; }
    if(!attendanceOk) { showTab('attendance'); toast('Run the attendance setup SQL before generating attendance-based payroll.', false); window.scrollTo({ top: 0 }); return; }
    if(!securityOk) { showTab('payroll'); toast('Run the staff security setup SQL shown at the top of the page first.', false); window.scrollTo({ top: 0 }); return; }
    const month = curMonth(), missing = eligibleStaff(month).filter(s => !payMap[s.staffId + '|' + month]);
    if(monthEnd(month) > todayStr()) { toast('Generate payroll after the salary month has ended.', false); return; }
    if(!missing.length) { toast(`The salary sheet for ${monthLabel(month)} is already complete.`); return; }

    showLoading('Loading monthly attendance...');
    try {
        if(incrementsOk) {
            const incrementResponse = await ERP.db.request('staff_salary_increments',
                `select=staff_id,effective_month,new_salary&effective_month=lte.${encodeURIComponent(month)}`);
            if(!incrementResponse.ok) throw new Error('Could not refresh salary increments before payroll generation: ' + await incrementResponse.text());
            const rows = await incrementResponse.json();
            if(!Array.isArray(rows)) throw new Error('Supabase returned invalid salary increments for payroll generation.');
            salaryIncrements = rows;
        }
        const response = await ERP.db.request('staff_attendance',
            `select=staff_id,staff_name,attendance_date,status,absence_exempt,late_exempt,note&attendance_date=gte.${monthStart(month)}&attendance_date=lte.${monthEnd(month)}`);
        if(!response.ok) throw new Error('Could not read monthly attendance: ' + await response.text());
        const rows = await response.json();
        if(!Array.isArray(rows)) throw new Error('Supabase returned invalid monthly attendance data.');
        const dates = monthSchoolDays(month);
        payrollGenDrafts = missing.map(s => {
            const salaryStaff = { ...s, base: salaryForMonth(s, month) };
            const expectedDates = dates.filter(d => (!s.joining || s.joining <= d) &&
                (s.status === 'Active' || (s.leaving && s.leaving >= d)));
            const staffRows = rows.filter(r => r.staff_id === salaryStaff.staffId &&
                expectedDates.includes(String(r.attendance_date).slice(0, 10)));
            const byDate = new Map(staffRows.map(r => [String(r.attendance_date).slice(0, 10), r]));
            const absences = staffRows.filter(r => r.status === 'absent').length;
            const excusedLeaves = staffRows.filter(r => r.status === 'absent' && r.absence_exempt).length;
            const deductibleLeaves = absences - excusedLeaves;
            return { staff: salaryStaff, expectedDates, byDate, markedDays: staffRows.length, missingDays: expectedDates.length - staffRows.length,
                absenceCount: absences, excusedLeaves, defaultLeaves: deductibleLeaves, lateCount: staffRows.filter(r => r.status === 'late' && !r.late_exempt).length,
                excusedLates: staffRows.filter(r => r.status === 'late' && r.late_exempt).length,
                defaultLateDeductionDays: Math.floor(staffRows.filter(r => r.status === 'late' && !r.late_exempt).length / 3) };
        });
        renderPayrollGeneration(month);
        openModal('genPayrollModal');
    } catch (error) {
        toast(error.message || 'Could not load monthly attendance.', false);
    } finally {
        hideLoading();
    }
}

