function isSunday(date) { return new Date(`${date}T00:00:00Z`).getUTCDay() === 0; }
function monthSchoolDays(month) {
    let [year, monthNumber] = month.split('-').map(Number), days = [];
    let date = new Date(Date.UTC(year, monthNumber - 1, 1));
    while(date.getUTCMonth() === monthNumber - 1) {
        if(date.getUTCDay() !== 0) days.push(date.toISOString().slice(0, 10));
        date.setUTCDate(date.getUTCDate() + 1);
    }
    return days;
}
