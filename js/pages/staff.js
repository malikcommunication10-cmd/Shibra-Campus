async function saveStaffAttendanceMonth() {
    const draft = staffAttendanceMonthDraft;
    if(!draft || !attendanceOk) return;
    const changes = [];
    for(const [date, row] of Object.entries(draft.rows).sort(([a], [b]) => a.localeCompare(b))) {
        if(!row) continue;
        const old = row._original || null;
        const timeIn = String(row.time_in || '').trim() || null;
        const timeOut = String(row.time_out || '').trim() || null;
        let status = row.status || '';
        if(!old && !status && !timeIn && !timeOut && !String(row.note || '').trim()) continue;
        if(!status && (timeIn || timeOut)) status = 'present';
        if(!status) {
            toast(`${fmtDate(date)}: In/Out edit karne ke liye status select karein.`, false);
            return;
        }
        const sameStatus = !!old && old.status === status;
        const absenceExempt = sameStatus && !!old.absence_exempt && status === 'absent';
        const lateExempt = sameStatus && !!old.late_exempt && status === 'late';
        const note = String(row.note || '').trim() || null;
        if((absenceExempt || lateExempt) && !note) {
            toast(`${fmtDate(date)}: Excused attendance ke liye Remarks mein wajah likhein.`, false);
            return;
        }
        if(old && old.status === status && String(old.time_in || '').slice(0, 5) === (timeIn || '')
            && String(old.time_out || '').slice(0, 5) === (timeOut || '')
            && String(old.note || '') === (note || '')
            && !!old.absence_exempt === absenceExempt && !!old.late_exempt === lateExempt) continue;
        changes.push({
            staff_id: draft.member.staffId, staff_name: draft.member.name, attendance_date: date,
            status, time_in: timeIn, time_out: timeOut, note,
            absence_exempt: absenceExempt, late_exempt: lateExempt
        });
    }
    if(!changes.length) { toast('Koi attendance change nahi mila.'); return; }
    const button = $('saveStaffAttendanceMonth');
    button.disabled = true;
    showLoading(`${changes.length} attendance record save ho rahe hain...`);
    try {
        const c = getSupabaseConfig();
        const response = await fetch(`${c.url}/rest/v1/staff_attendance?on_conflict=staff_id,attendance_date`, {
            method: 'POST',
            headers: sbHeaders({ ...JSON_H, Prefer: 'resolution=merge-duplicates,return=minimal' }),
            body: JSON.stringify(changes)
        });
        if(!response.ok) throw new Error('Attendance save nahi hui: ' + await response.text());
        closeModal('staffAttendanceMonthModal');
        let refreshError = await refreshAttendanceRangeAfterSave();
        if(changes.some(row => row.attendance_date === attendanceDate)) {
            try { await loadAttendance(attendanceDate); }
            catch(error) {
                console.error('Attendance saved, but selected-day refresh failed:', error);
                refreshError += ` Selected-day view refresh nahi hua: ${error.message || 'unknown error'}`;
            }
        }
        toast(`${changes.length} attendance changes save ho gayin. Purana payroll apne aap recalculate nahi hota.${refreshError}`, !refreshError);
    } catch(error) {
        toast(error.message || 'Monthly attendance save nahi hui.', false);
    } finally {
        hideLoading();
        button.disabled = false;
    }
}
function changeAttendanceDate(date) {
    if(!date || date > todayStr()) {
        $('attendanceDate').value = attendanceDate || todayStr();
        toast('Attendance can only be entered for today or an earlier date.', false);
        return;
    }
    if(attendanceDirty) {
        $('attendanceDate').value = attendanceDate || todayStr();
        confirmBox('Discard unsaved attendance changes and open another date?', 'Discard', () => {
            $('attendanceDate').value = date;
            loadAttendance(date).catch(e => {
                $('attendanceDate').value = attendanceDate || todayStr();
                toast(e.message, false);
            });
        });
        return;
    }
    let previous = attendanceDate;
    loadAttendance(date).catch(e => {
        $('attendanceDate').value = previous || todayStr();
        toast(e.message, false);
    });
}
async function saveAttendance() {
    if(!attendanceOk) { toast('Run the attendance setup SQL first.', false); return; }
    let date = $('attendanceDate').value, members = attendanceStaff(date);
    if(isSunday(date)) { toast('Sunday is an automatic weekly off; attendance is not marked.', false); return; }
    let unmarked = members.filter(s => !attendanceDrafts[s.staffId] || !['present', 'absent', 'late'].includes(attendanceDrafts[s.staffId].status));
    if(unmarked.length) { toast(`Mark attendance for all staff first (${unmarked.length} unmarked).`, false); return; }
    let exemptions = members.filter(s => {
        let row = attendanceDrafts[s.staffId];
        return row && (row.absenceExempt || row.lateExempt) && !row.note.trim();
    });
    if(exemptions.length) { toast(`Add a reason in Remarks for each exemption (${exemptions.map(s => s.name).join(', ')}).`, false); return; }
    if(members.some(s => {
        let row = attendanceDrafts[s.staffId] || {};
        return (row.absenceExempt || row.lateExempt) && (!ME || ME.role !== 'Admin');
    })) { toast('Only an Admin can approve attendance exemptions.', false); return; }
    showLoading('Saving attendance...');
    try {
        let c = getSupabaseConfig(), inserts = [], updates = [];
        members.forEach(s => {
            let draft = attendanceDrafts[s.staffId], old = attendanceByStaff[s.staffId];
            let row = { staff_id: s.staffId, staff_name: s.name, attendance_date: date, status: draft.status, note: draft.note.trim() || null,
                absence_exempt: !!draft.absenceExempt, late_exempt: !!draft.lateExempt };
            if(!old) inserts.push(row);
            else if(old.status !== row.status || (old.note || null) !== row.note || old.staff_name !== row.staff_name
                || !!old.absence_exempt !== row.absence_exempt || !!old.late_exempt !== row.late_exempt) updates.push(row);
        });
        for(let row of updates) {
            let res = await fetch(`${c.url}/rest/v1/staff_attendance?staff_id=eq.${encodeURIComponent(row.staff_id)}&attendance_date=eq.${encodeURIComponent(date)}`, {
                method: 'PATCH', headers: sbHeaders({ ...JSON_H, "Prefer": "return=minimal" }), body: JSON.stringify({ staff_name: row.staff_name, status: row.status, note: row.note, absence_exempt: row.absence_exempt, late_exempt: row.late_exempt })
            });
            if(!res.ok) throw new Error('Could not update attendance: ' + await res.text());
        }
        if(inserts.length) {
            let res = await fetch(`${c.url}/rest/v1/staff_attendance`, {
                method: 'POST', headers: sbHeaders({ ...JSON_H, "Prefer": "return=minimal" }), body: JSON.stringify(inserts)
            });
            if(!res.ok) throw new Error('Could not add attendance: ' + await res.text());
        }
        attendanceDirty = false;
        await loadAttendance(date);
        const refreshError = await refreshAttendanceRangeAfterSave();
        toast(`Attendance saved for ${members.length} staff member(s).${refreshError}`, !refreshError);
    } catch(e) {
        toast(`${e.message || 'Could not save attendance.'} Review this date before retrying.`, false);
    } finally { hideLoading(); }
}
