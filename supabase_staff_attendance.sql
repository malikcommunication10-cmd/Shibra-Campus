create or replace function public.list_payroll_waiver_candidates()
returns table (
    payroll_id bigint,
    staff_id text,
    staff_name text,
    month text,
    current_leave_days integer,
    current_late_days integer
)
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
begin
    if not (public.app_has_page_permission('accounts', 'v') or public.app_has_page_permission('accounts', 'a') or public.app_has_page_permission('accounts', 'e')) then
        raise exception 'Accounts permission is required to request a payroll waiver.';
    end if;

    return query
        select p.id, p.staff_id, coalesce(p.staff_name, p.staff_id), p.month,
            greatest(0, floor(coalesce(p.leaves, 0))::integer),
            greatest(0, coalesce(p.late_deduction_days, floor(greatest(0, coalesce(p.late_count, 0)) / 3.0)::integer))
        from public.payroll p
        where p.status = 'Unpaid'
          and (
            greatest(0, floor(coalesce(p.leaves, 0))::integer) > 0
            or greatest(0, coalesce(p.late_deduction_days, floor(greatest(0, coalesce(p.late_count, 0)) / 3.0)::integer)) > 0
          )
          and not exists (
            select 1 from public.payroll_waiver_requests r
            where r.payroll_id = p.id and r.status = 'Pending'
          )
        order by p.month desc, p.staff_name;
end;
$$;

create or replace function public.request_payroll_waiver(
    p_payroll_id bigint,
    p_leave_days integer,
    p_late_days integer,
    p_reason text
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
    v_payroll public.payroll%rowtype;
    v_leave_days integer;
    v_late_days integer;
    v_request_id bigint;
    v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
    if not (public.app_has_page_permission('accounts', 'v') or public.app_has_page_permission('accounts', 'a') or public.app_has_page_permission('accounts', 'e')) then
        raise exception 'Accounts permission is required to request a payroll waiver.';
    end if;
    if nullif(btrim(coalesce(p_reason, '')), '') is null or length(btrim(p_reason)) > 300 then
        raise exception 'Enter a waiver reason of 1 to 300 characters.';
    end if;
    if p_leave_days is null or p_late_days is null or p_leave_days < 0 or p_late_days < 0 then
        raise exception 'Requested deduction days must be whole numbers of zero or more.';
    end if;

    select * into v_payroll
    from public.payroll p
    where p.id = p_payroll_id
    for update;
    if not found or v_payroll.status <> 'Unpaid' then
        raise exception 'Only an existing unpaid payroll can have a waiver requested.';
    end if;

    v_leave_days := greatest(0, floor(coalesce(v_payroll.leaves, 0))::integer);
    v_late_days := greatest(0, coalesce(v_payroll.late_deduction_days, floor(greatest(0, coalesce(v_payroll.late_count, 0)) / 3.0)::integer));
    if p_leave_days > v_leave_days or p_late_days > v_late_days then
        raise exception 'Requested deduction days cannot exceed the current payroll deduction.';
    end if;
    if p_leave_days = v_leave_days and p_late_days = v_late_days then
        raise exception 'Reduce at least one off/leave or late deduction day.';
    end if;

    insert into public.payroll_waiver_requests (
        payroll_id, staff_id, staff_name, month,
        current_leave_days, requested_leave_days, current_late_days, requested_late_days,
        reason, requested_by
    ) values (
        v_payroll.id, v_payroll.staff_id, coalesce(v_payroll.staff_name, v_payroll.staff_id), v_payroll.month,
        v_leave_days, p_leave_days, v_late_days, p_late_days,
        btrim(p_reason), v_email
    ) returning id into v_request_id;
    return v_request_id;
end;
$$;

create or replace function public.review_payroll_waiver(
    p_request_id bigint,
    p_approve boolean,
    p_admin_note text default null
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
    v_request public.payroll_waiver_requests%rowtype;
    v_payroll public.payroll%rowtype;
    v_current_late_days integer;
    v_daily numeric;
    v_salary_amount numeric;
    v_leave_deduction numeric;
    v_late_deduction numeric;
    v_before_security numeric;
    v_net numeric;
    v_notes text;
    v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
    if not public.app_is_admin() then
        raise exception 'Only an Admin can review payroll waiver requests.';
    end if;
    if p_approve is null then
        raise exception 'Choose approve or reject.';
    end if;
    if length(btrim(coalesce(p_admin_note, ''))) > 300 then
        raise exception 'Admin remarks must be 300 characters or fewer.';
    end if;

    select * into v_request
    from public.payroll_waiver_requests r
    where r.id = p_request_id
    for update;
    if not found or v_request.status <> 'Pending' then
        raise exception 'This waiver request is no longer pending.';
    end if;

    update public.payroll_waiver_requests
    set status = case when p_approve then 'Approved' else 'Rejected' end,
        reviewed_by = v_email,
        reviewed_at = now(),
        admin_note = nullif(btrim(coalesce(p_admin_note, '')), '')
    where id = v_request.id;

    if p_approve then
        select * into v_payroll
        from public.payroll p
        where p.id = v_request.payroll_id
        for update;
        if not found or v_payroll.status <> 'Unpaid' then
            raise exception 'Payroll must still exist and be unpaid before approval.';
        end if;

        v_current_late_days := greatest(0, coalesce(v_payroll.late_deduction_days, floor(greatest(0, coalesce(v_payroll.late_count, 0)) / 3.0)::integer));
        if v_request.requested_leave_days > floor(coalesce(v_payroll.leaves, 0))::integer
          or v_request.requested_late_days > v_current_late_days
          or (v_request.requested_leave_days = floor(coalesce(v_payroll.leaves, 0))::integer
            and v_request.requested_late_days = v_current_late_days) then
            raise exception 'The payroll deduction has changed since this request was submitted.';
        end if;

        v_daily := coalesce(v_payroll.base_salary, 0) / 30.0;
        v_salary_amount := round(v_daily * least(30, greatest(0, coalesce(v_payroll.salary_days, 30))));
        v_leave_deduction := round(v_daily * v_request.requested_leave_days);
        v_late_deduction := round(v_daily * v_request.requested_late_days);
        v_before_security := greatest(0, round(v_salary_amount - v_leave_deduction - v_late_deduction
          + coalesce(v_payroll.bonus, 0) - coalesce(v_payroll.fine, 0) - coalesce(v_payroll.advance, 0)));
        v_net := greatest(0, v_before_security - coalesce(v_payroll.security_deduction, 0));
        v_notes := concat_ws(' ', nullif(btrim(coalesce(v_payroll.notes, '')), ''),
            format('Admin approved Accounts waiver request #%s: %s', v_request.id, v_request.reason));

        update public.payroll
        set leaves = v_request.requested_leave_days,
            leave_deduction = v_leave_deduction,
            late_deduction_days = v_request.requested_late_days,
            late_deduction = v_late_deduction,
            net_salary = v_net,
            status = case when coalesce(v_payroll.paid_amount, 0) > 0 and coalesce(v_payroll.paid_amount, 0) >= v_net then 'Paid' else 'Unpaid' end,
            notes = v_notes
        where id = v_payroll.id;
    end if;

end;
$$;

